#!/usr/bin/env python3
"""Emit a C++ header embedding the CVX8897 register tables.

The tables share one register order (251 writes) and differ only in the values,
so the header exposes a single `kRegOrder` array plus one value array per mode,
and a `Table` list to look them up by name or by `Mode`.

Usage:
    python3 gen_cvx8897_header.py cvx8897_tables.json > cvx8897_tables.h
"""
import argparse
import json


def arr(vals, per=16):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(f"0x{v:02x}" for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def cname(name):
    return name  # already [A-Za-z0-9_]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("json", nargs="?", default="cvx8897_tables.json")
    args = ap.parse_args()

    t = json.load(open(args.json))
    reg_order = t["reg_order"]
    modes = t["modes"]

    out = []
    out.append("// Generated by tools/cvx8897/gen_cvx8897_header.py - do not edit.")
    out.append("// Source: CVX8897 frame-rate converter, extracted from libC877Driver.dylib")
    out.append("// (macOS) and cross-checked against avmu3_x64.sys (Windows).")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("#include <cstddef>")
    out.append("")
    out.append("namespace cvx8897 {")
    out.append("")
    out.append("// 7-bit I2C address of the CVX8897 on the FX3 bridge")
    out.append("// (UsbStream::sendI2cWrite emits `01 18 01 <reg> <val>`).")
    out.append("inline constexpr uint8_t kI2cAddress = 0x18;")
    out.append("")
    out.append(f"inline constexpr std::size_t kRegCount = {len(reg_order)};")
    out.append("")
    out.append("// Register write order shared by every mode.")
    out.append(f"inline constexpr uint8_t kRegOrder[kRegCount] = {{")
    out.append(arr(reg_order))
    out.append("};")
    out.append("")
    for name, vals in modes.items():
        out.append(f"inline constexpr uint8_t k{name}[kRegCount] = {{")
        out.append(arr(vals))
        out.append("};")
        out.append("")
    out.append("enum class Mode {")
    for name in modes:
        out.append(f"    {name},")
    out.append("};")
    out.append("")
    out.append("struct Table {")
    out.append("    Mode mode;")
    out.append("    const char* name;")
    out.append("    const uint8_t* values;")
    out.append("};")
    out.append("")
    out.append("inline constexpr Table kTables[] = {")
    for name in modes:
        out.append(f'    {{Mode::{name}, "{name}", k{name}}},')
    out.append("};")
    out.append("")
    out.append("inline constexpr std::size_t kTableCount = sizeof(kTables) / sizeof(kTables[0]);")
    out.append("")
    out.append("}  // namespace cvx8897")
    out.append("")

    print("\n".join(out))


if __name__ == "__main__":
    main()
